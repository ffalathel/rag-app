from rank_bm25 import BM25Okapi
from nltk.tokenize import word_tokenize
from nltk.corpus import stopwords

STOP_WORDS = set(stopwords.words('english'))

def tokenize_for_bm25(text):
    text = text.lower()
    tokens = word_tokenize(text)
    return [t for t in tokens if (t.isalnum() or '$' in t or '%' in t) and t not in STOP_WORDS]

class BM25Index:
    def __init__(self, documents):
        self.documents = documents
        self.corpus_tokens = [tokenize_for_bm25(doc.text) for doc in documents]
        self.bm25 = BM25Okapi(self.corpus_tokens)
        print(f"  ✅ BM25 index: {len(documents)} documents.")

    def search(self, query, top_k=10):
        scores = self.bm25.get_scores(tokenize_for_bm25(query))
        top_indices = np.argsort(scores)[::-1][:top_k]
        return [(self.documents[i], float(scores[i])) for i in top_indices if scores[i] > 0]

