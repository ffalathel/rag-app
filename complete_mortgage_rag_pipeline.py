def vector_search(query, index, top_k=10):
    """Vector search wrapper returning (Document, score) tuples."""
    nodes = VectorIndexRetriever(index=index, similarity_top_k=top_k).retrieve(query)
    return [(Document(text=n.get_text(), metadata=n.metadata), n.score or 0.0) for n in nodes]


def reciprocal_rank_fusion(result_lists, k=60):
    """Merge ranked lists with RRF. Returns [(doc, rrf_score)]."""
    doc_scores, doc_objects = {}, {}
    for result_list in result_lists:
        for rank, (doc, _) in enumerate(result_list):
            key = doc.text[:200].strip()
            if key not in doc_scores:
                doc_scores[key] = 0.0
                doc_objects[key] = doc
            doc_scores[key] += 1.0 / (k + rank + 1)
    sorted_keys = sorted(doc_scores, key=lambda x: doc_scores[x], reverse=True)
    return [(doc_objects[k], doc_scores[k]) for k in sorted_keys]


def hybrid_retrieve(query, vector_idx, top_k=10):
    """Hybrid: Vector + BM25 → RRF fusion."""
    vector_results = vector_search(query, vector_idx, top_k=top_k)

    if USE_LLAMAINDEX_BM25:
        bm25_nodes = llamaindex_bm25.retrieve(query)
        bm25_results = [(Document(text=n.get_text(), metadata=n.metadata), n.score or 0.0) for n in bm25_nodes]
    else:
        bm25_results = bm25_index.search(query, top_k=top_k)

    fused = reciprocal_rank_fusion([vector_results, bm25_results], k=60)
    return fused[:top_k]


