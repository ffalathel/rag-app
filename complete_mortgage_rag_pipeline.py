from sklearn.metrics.pairwise import cosine_similarity

# ─── Mortgage section header patterns ───
SECTION_PATTERNS = [
    r'(?:^|\n)(?:SECTION|Section|ARTICLE|Article)\s+\d+[.:]?\s+[A-Z]',
    r'(?:^|\n)\d{1,2}\.\s+[A-Z][A-Za-z]',
    r'(?:^|\n)([A-Z][A-Z\s]{5,})(?:\n|$)',
    r'(?:^|\n)\([a-z]\)\s',
    r'(?:^|\n)\([ivx]+\)\s',
]

def find_section_breaks(text):
    breaks = []
    for pattern in SECTION_PATTERNS:
        for match in re.finditer(pattern, text):
            breaks.append((match.start(), match.group().strip()))
    breaks.sort(key=lambda x: x[0])
    return breaks

def recursive_chunk(text, max_tokens=512, min_tokens=50):
    """Split by section headers → paragraphs → sentences."""
    breaks = find_section_breaks(text)
    if breaks:
        sections = []
        if breaks[0][0] > 0:
            preamble = text[:breaks[0][0]].strip()
            if len(preamble) > min_tokens:
                sections.append((preamble, "Preamble"))
        for i, (pos, header) in enumerate(breaks):
            end = breaks[i + 1][0] if i + 1 < len(breaks) else len(text)
            section_text = text[pos:end].strip()
            if section_text:
                sections.append((section_text, header))
    else:
        sections = [(text, "Full Page")]

    chunks = []
    for section_text, section_title in sections:
        if len(section_text.split()) * 1.3 <= max_tokens:
            chunks.append((section_text, section_title))
        else:
            paragraphs = re.split(r'\n\s*\n', section_text)
            current_chunk = ""
            for para in paragraphs:
                para = para.strip()
                if not para: continue
                test_chunk = current_chunk + "\n\n" + para if current_chunk else para
                if len(test_chunk.split()) * 1.3 <= max_tokens:
                    current_chunk = test_chunk
                else:
                    if current_chunk: chunks.append((current_chunk, section_title))
                    current_chunk = para
            if current_chunk: chunks.append((current_chunk, section_title))

    return [(t, s) for t, s in chunks if len(t.split()) >= 10]

def semantic_merge(chunks_with_titles, threshold=0.75, max_tokens=600):
    """Merge adjacent chunks if semantically similar."""
    if len(chunks_with_titles) <= 1: return chunks_with_titles
    texts = [c[0] for c in chunks_with_titles]
    embeddings = semantic_model.encode(texts, normalize_embeddings=True)
    merged = [chunks_with_titles[0]]
    for i in range(1, len(chunks_with_titles)):
        prev_text, prev_title = merged[-1]
        curr_text, curr_title = chunks_with_titles[i]
        sim = cosine_similarity(embeddings[i-1].reshape(1,-1), embeddings[i].reshape(1,-1))[0][0]
        combined = prev_text + "\n\n" + curr_text
        if sim >= threshold and len(combined.split()) * 1.3 <= max_tokens:
            merged[-1] = (combined, prev_title)
        else:
            merged.append((curr_text, curr_title))
    return merged

def smart_chunk_page(page_text, max_tokens=512, merge_threshold=0.75):
    """Recursive split → semantic merge."""
    raw = recursive_chunk(page_text, max_tokens=max_tokens)
    return semantic_merge(raw, threshold=merge_threshold)

