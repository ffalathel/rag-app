def preprocess_image(pil_image):
    """Preprocess scanned page: grayscale → rescale 1.5x → adaptive threshold → bilateral denoise."""
    img = np.array(pil_image)
    if len(img.shape) == 3:
        gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    else:
        gray = img
    h, w = gray.shape
    scaled = cv2.resize(gray, (int(w * 1.5), int(h * 1.5)), interpolation=cv2.INTER_CUBIC)
    thresh = cv2.adaptiveThreshold(scaled, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY, 15, 8)
    denoised = cv2.bilateralFilter(thresh, 9, 75, 75)
    return denoised

def ocr_with_paddle(image_array):
    """PaddleOCR — better for dense forms, tables, mixed layouts."""
    try:
        results = paddle_ocr.ocr(image_array, cls=True)
        if not results or not results[0]:
            return ""
        return " ".join([line[1][0] for line in results[0] if line[1][1] > 0.5])
    except Exception as e:
        print(f"  ⚠️ PaddleOCR error: {e}")
        return ""

def ocr_with_tesseract(image_array):
    """Tesseract fallback — reliable for clean typed pages."""
    try:
        return pytesseract.image_to_string(Image.fromarray(image_array)).strip()
    except Exception as e:
        print(f"  ⚠️ Tesseract error: {e}")
        return ""

MIN_TEXT_LENGTH = 50

def ingest_pdf(pdf_path):
    """Ingest a single PDF. Returns list of page dicts."""
    filename = os.path.basename(pdf_path)
    doc = fitz.open(pdf_path)
    pages_data = []

    digital_texts = [page.get_text().strip() for page in doc]
    needs_ocr = any(len(t) < MIN_TEXT_LENGTH for t in digital_texts)
    page_images = convert_from_path(pdf_path, dpi=200) if needs_ocr else None

    if needs_ocr:
        print(f"  📷 Some pages need OCR — converting {filename} to images...")

    for i, page in enumerate(doc):
        text = digital_texts[i]
        source_type = "digital"

        if len(text) < MIN_TEXT_LENGTH and page_images:
            print(f"  🔍 OCR on page {i+1} of {filename}")
            preprocessed = preprocess_image(page_images[i])
            text = ocr_with_paddle(preprocessed)
            source_type = "ocr_paddle"
            if len(text) < MIN_TEXT_LENGTH:
                print(f"    ↪ PaddleOCR insufficient, trying Tesseract...")
                text = ocr_with_tesseract(preprocessed)
                source_type = "ocr_tesseract"

        pages_data.append({
            "filename": filename, "page_number": i + 1,
            "text": text, "source_type": source_type, "doc_type": "unknown"
        })

    doc.close()
    print(f"  ✅ {filename}: {len(pages_data)} pages ingested.")
    return pages_data

def ingest_all_pdfs(pdf_folder):
    """Ingest all PDFs from a folder."""
