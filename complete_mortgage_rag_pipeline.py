def detect_table_content(text):
    """Heuristic: does this chunk contain tabular data?"""
    indicators = 0
    if len(re.findall(r'^.*\d+[.,]\d+.*\d+[.,]\d+.*$', text, re.MULTILINE)) >= 3: indicators += 1
    if len(re.findall(r'^.+\s{3,}.+$', text, re.MULTILINE)) >= 3: indicators += 1
    if '|' in text or '\t' in text: indicators += 1
    if len(re.findall(r'\$[\d,]+', text)) >= 3: indicators += 1
    return indicators >= 2

