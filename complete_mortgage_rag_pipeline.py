"""## Full Pipeline: `ask_v3()` (All Phases Combined)"""

def ask_v3(
    query,
    vector_idx=None,
    use_rewrite=True,
    use_decomposition=True,
    hybrid_top_k=10,
    rerank_top_n=5,
    max_context_tokens=2000,
    verbose=True
):
    """
    Complete RAG pipeline:
    Rewrite → Decompose → Hybrid Retrieve → Rerank → Cleanup → LLM Answer.
    """
    if vector_idx is None: vector_idx = vector_index_v2
    debug = {"original_query": query}

    # 1. Query Rewriting
    rewritten = rewrite_query(query, llm) if use_rewrite else query
    debug["rewritten_query"] = rewritten
    if verbose: print(f"  ✏️  Rewritten: {rewritten}")

    # 2. Query Decomposition
    sub_queries = decompose_query(rewritten, llm) if use_decomposition else [rewritten]
    debug["sub_queries"] = sub_queries
    if verbose: print(f"  🔀 Sub-queries: {sub_queries}")

    # 3. Hybrid Retrieval per sub-query
    all_retrieved = []
    for sq in sub_queries:
        results = hybrid_retrieve(sq, vector_idx, top_k=hybrid_top_k)
        all_retrieved.extend(results)
        if verbose: print(f"  🔍 '{sq[:50]}...' → {len(results)} results")

    # Dedup across sub-queries
    seen = set()
    unique = []
    for doc, score in all_retrieved:
        key = doc.text[:200].strip()
        if key not in seen:
            seen.add(key)
            unique.append((doc, score))

    if verbose: print(f"  📦 Unique results: {len(unique)}")
    if not unique:
        return {"answer": "No relevant documents found.", "sources": [],
                "num_chunks_used": 0, "confidence": 0.0, "debug": debug}

    # 4. Cross-Encoder Reranking
    reranked = rerank_results(query, unique, top_n=rerank_top_n)
    if verbose: print(f"  🏆 Reranked: {len(reranked)}")

    # 5. Context Cleanup
    cleaned = clean_context(reranked, max_context_tokens=max_context_tokens)
    if verbose: print(f"  🧹 After cleanup: {len(cleaned)}")

    # 6. Build prompt + generate
    context_parts = []
    for i, (doc, score) in enumerate(cleaned):
        m = doc.metadata
        context_parts.append(
            f"[Source {i+1}: {m.get('filename','?')}, Page {m.get('page_number','?')}, "
            f"Type: {m.get('doc_type','?')}, Section: {m.get('section_title','?')}]\n{doc.text}"
        )

    context_block = "\n\n---\n\n".join(context_parts)

    prompt = f"""You are a mortgage document analysis assistant. Answer ONLY from the provided context.
If the answer is not in the context, say "I cannot find this information in the provided documents."
Be precise with financial figures, dates, and legal terms. Cite sources with filename and page number.

=== CONTEXT ===
{context_block}
=== END CONTEXT ===

Question: {query}

Answer (with citations):"""

    answer = str(llm.complete(prompt)).strip()

    # 7. Format output
    sources, scores = [], []
    for doc, score in cleaned:
        m = doc.metadata
        sources.append({
            "filename": m.get("filename", "?"), "page_number": m.get("page_number", "?"),
            "doc_type": m.get("doc_type", "unknown"), "section_title": m.get("section_title", ""),
            "score": round(float(score), 4),
            "preview": " ".join(doc.text.split()[:25]) + "..."
        })
        scores.append(float(score))

    return {
        "answer": answer, "sources": sources,
        "num_chunks_used": len(sources),
        "confidence": round(np.mean(scores), 4) if scores else 0.0,
        "debug": debug
    }

