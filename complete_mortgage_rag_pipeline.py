from sklearn.metrics.pairwise import cosine_similarity as cos_sim

def rerank_results(query, results, top_n=5):
    """Cross-encoder reranking."""
    if not results: return []
    pairs = [(query, doc.text[:512]) for doc, _ in results]
    ce_scores = cross_encoder.predict(pairs)
    scored = list(zip([doc for doc, _ in results], ce_scores))
    scored.sort(key=lambda x: x[1], reverse=True)
    return scored[:top_n]


def clean_context(reranked, min_score=-5.0, dedup_threshold=0.92, max_context_tokens=2000):
    """Filter by score, remove near-duplicates, enforce token budget."""
    if not reranked: return []

    # Score filter
    filtered = [(d, s) for d, s in reranked if s >= min_score]
    if not filtered: filtered = [reranked[0]]

    # Dedup
    if len(filtered) > 1:
        texts = [d.text for d, _ in filtered]
        embs = semantic_model.encode(texts, normalize_embeddings=True)
        keep = [0]
        for i in range(1, len(filtered)):
            if all(cos_sim(embs[i].reshape(1,-1), embs[j].reshape(1,-1))[0][0] < dedup_threshold for j in keep):
                keep.append(i)
        filtered = [filtered[i] for i in keep]

    # Token budget
    final, total = [], 0
    for doc, score in filtered:
        tokens = len(doc.text.split()) * 1.3
        if total + tokens <= max_context_tokens:
            final.append((doc, score))
            total += tokens
        else: break
    return final


