def decompose_query(user_query, llm):
    """Break complex questions into 2-4 focused sub-queries."""
    prompt = f"""You are a query decomposition assistant for a mortgage document search system.
If the question is simple, return just the original question.
If complex, break into 2-4 focused sub-questions.
Return ONLY the sub-questions, one per line. No numbering, no bullets.

Question: "{user_query}"

Sub-questions:"""
    try:
        response = llm.complete(prompt)
        sub_queries = []
        for line in str(response).strip().split('\n'):
            line = line.strip().strip('-•*0123456789.)').strip().strip('"\'')
            if len(line) > 10: sub_queries.append(line)
        return sub_queries[:4] if sub_queries else [user_query]
    except:
        return [user_query]


