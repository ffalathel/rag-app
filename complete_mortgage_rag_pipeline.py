def ask(query, index=None, top_k=10, rerank_top_n=3):
    """
    Phase 1 RAG: Vector search → Rerank → LLM → Answer + sources.
    """
    if index is None:
        index = vector_index

    retriever = VectorIndexRetriever(index=index, similarity_top_k=top_k)
    reranker_inst = SentenceTransformerRerank(
        model="cross-encoder/ms-marco-MiniLM-L-6-v2", top_n=rerank_top_n
    )
    query_engine = RetrieverQueryEngine(
        retriever=retriever,
        response_synthesizer=get_response_synthesizer(response_mode="compact"),
        node_postprocessors=[reranker_inst]
    )
    response = query_engine.query(query)

    sources, scores = [], []
    for node in response.source_nodes:
        score = node.score if node.score else 0.0
        sources.append({
            "filename": node.metadata.get("filename", "?"),
            "page_number": node.metadata.get("page_number", "?"),
            "doc_type": node.metadata.get("doc_type", "unknown"),
            "score": round(score, 4),
            "preview": " ".join(node.get_text().split()[:25]) + "..."
        })
        scores.append(score)

    return {
        "answer": str(response),
        "sources": sources,
        "num_chunks_used": len(sources),
        "confidence": round(float(np.mean(scores)), 4) if scores else 0.0
    }

